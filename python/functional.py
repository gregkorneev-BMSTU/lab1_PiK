def read_number(name):
    # Повторяем запрос, если значение не удалось преобразовать в число.
    while True:
        try:
            return int(input("Введите " + name + ": "))
        except ValueError:
            print("Введите число")


def print_roots(y):
    # Возвращаем True, если для y нашлись действительные корни x.
    if y > 0:
        x = y ** 0.5
        # У положительного y два корня: y в степени 0.5 и его минус.
        print("Корни:", x, -x)
        return True
    elif y == 0:
        print("Корень: 0")
        return True
    # При отрицательном y действительных x нет.
    return False


def solve(a, b, c):
    # Используем замену y = x^2 и вычисляем дискриминант.
    d = b * b - 4 * a * c
    print("Дискриминант:", d)

    # Отдельно решаем вырожденный случай A = 0.
    if a == 0:
        if b == 0:
            if c == 0:
                print("Подходит любое действительное x")
            else:
                print("Корней нет")
        else:
            y1 = -c / b
            # Проверяем, можно ли получить действительные x из y1.
            if not print_roots(y1):
                print("Действительных корней нет")
        return

    # match выбирает нужную формулу по значению дискриминанта.
    match d:
        # Условие проверяет отрицательный дискриминант.
        case value if value < 0:
            print("Действительных корней нет")

        # Точный шаблон для нулевого дискриминанта.
        case 0:
            # При D = 0 есть одно значение y.
            y1 = -b / (2 * a)
            if not print_roots(y1):
                print("Действительных корней нет")

        # Остался случай положительного дискриминанта.
        case _:
            # Иначе D положительный, поэтому находим два значения y.
            y1 = (-b + d ** 0.5) / (2 * a)
            y2 = (-b - d ** 0.5) / (2 * a)

            # Если оба значения y отрицательные, действительных x нет.
            has_roots = print_roots(y1)
            if print_roots(y2):
                has_roots = True
            if not has_roots:
                print("Действительных корней нет")


def main():
    # Получаем три коэффициента с клавиатуры.
    a = read_number("A")
    b = read_number("B")
    c = read_number("C")

    # Запускаем решение с введёнными коэффициентами.
    solve(a, b, c)


if __name__ == "__main__":
    # Точка входа в программу.
    main()
