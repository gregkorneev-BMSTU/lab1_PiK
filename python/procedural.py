def read_number(name):
    # Повторяем ввод, пока строку не получится преобразовать в число.
    while True:
        try:
            # int переводит введённый текст в целое число.
            return int(input("Введите " + name + ": "))
        except ValueError:
            print("Введите число")


def solve(a, b, c):
    # Делаем замену y = x^2 и считаем дискриминант квадратного уравнения.
    d = b * b - 4 * a * c
    print("Дискриминант:", d)

    # Если A = 0, уравнение становится линейным относительно y.
    if a == 0:
        if b == 0:
            if c == 0:
                print("Подходит любое действительное x")
            else:
                print("Корней нет")
        else:
            # Из B*y + C = 0 находим y.
            y1 = -c / b
            if y1 > 0:
                # Для положительного y есть два корня: y в степени 0.5 и его минус.
                x1 = y1 ** 0.5
                x2 = -(y1 ** 0.5)
                print("Корни:", x1, x2)
            elif y1 == 0:
                print("Корень: 0")
            else:
                # Квадрат действительного числа не может быть отрицательным.
                print("Действительных корней нет")

    # При отрицательном D квадратное уравнение не имеет действительных y.
    elif d < 0:
        print("Действительных корней нет")

    # При D = 0 квадратное уравнение имеет одно значение y.
    elif d == 0:
        y1 = -b / (2 * a)
        if y1 > 0:
            x1 = y1 ** 0.5
            x2 = -(y1 ** 0.5)
            print("Корни:", x1, x2)
        elif y1 == 0:
            print("Корень: 0")
        else:
            print("Действительных корней нет")

    # При положительном D получаем два значения y.
    else:
        y1 = (-b + d ** 0.5) / (2 * a)
        y2 = (-b - d ** 0.5) / (2 * a)

        if y1 < 0 and y2 < 0:
            print("Действительных корней нет")

        if y1 > 0:
            # Каждое положительное y даёт два значения x.
            x1 = y1 ** 0.5
            x2 = -(y1 ** 0.5)
            print("Корни:", x1, x2)
        elif y1 == 0:
            print("Корень: 0")

        if y2 > 0:
            x1 = y2 ** 0.5
            x2 = -(y2 ** 0.5)
            print("Корни:", x1, x2)
        elif y2 == 0:
            print("Корень: 0")


def main():
    # Получаем три коэффициента с клавиатуры.
    a = read_number("A")
    b = read_number("B")
    c = read_number("C")

    # Передаём коэффициенты функции решения.
    solve(a, b, c)


if __name__ == "__main__":
    # Запускаем main только при запуске этого файла.
    main()
